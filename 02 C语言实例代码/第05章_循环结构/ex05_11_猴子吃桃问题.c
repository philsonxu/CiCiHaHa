/*
 * 例5.11 猴子吃桃问题（逆推法经典题）
 * 猴子第1天摘下若干桃子，当即吃了一半，又多吃一个；
 * 第2天又将剩下的桃子吃了一半，又多吃一个；
 * 以后每天都吃前一天剩下的一半零一个；
 * 到第10天早上想再吃时，只剩下一个桃子。求第1天共摘了多少桃。
 * 知识点：逆推思维、循环递推
 */
#include <stdio.h>

int main()
{
    int day, x1, x2;
    day = 9;
    x2 = 1;  /* 第10天早上只剩1个 */
    
    while (day > 0) {
        x1 = (x2 + 1) * 2;  /* 第1天的桃子数是第2天桃子数加1后的2倍 */
        x2 = x1;
        day--;
    }
    
    printf("第1天共摘了%d个桃子\n", x1);
    return 0;
}