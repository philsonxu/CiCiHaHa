/*
 * 例1.4 C程序结构说明
 * 知识点：预处理指令#include、注释写法、函数定义、主函数位置
 */

/* 这是一个包含头文件的预处理指令 */
#include <stdio.h>

/* 主函数，程序入口 */
int main()
{
    int a = 10, b = 20, sum;  /* 定义整型变量并初始化 */
    sum = a + b;              /* 计算两数之和 */
    printf("sum = %d\n", sum);/* 输出结果 */
    return 0;                 /* 主函数返回值，表示程序正常结束 */
}