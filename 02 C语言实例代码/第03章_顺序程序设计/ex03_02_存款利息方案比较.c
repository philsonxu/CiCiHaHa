/*
 * 例3.2 存款利息方案比较
 * 知识点：浮点运算、算术表达式、多种方案对比计算
 */
#include <stdio.h>
#include <math.h>

int main()
{
    float r5, r3, r2, r1, r0, p, p1, p2, p3, p4, p5;
    p = 1000;
    r5 = 0.0585;  /* 5年期年利率 */
    r3 = 0.054;   /* 3年期年利率 */
    r2 = 0.0468;  /* 2年期年利率 */
    r1 = 0.0414;  /* 1年期年利率 */
    r0 = 0.0072;  /* 活期年利率 */
    
    p1 = p * ((1 + r5) * 5);                     /* 一次存5年期 */
    p2 = p * (1 + 2 * r2) * (1 + 3 * r3);        /* 先存2年，再存3年 */
    p3 = p * (1 + 3 * r3) * (1 + 2 * r2);        /* 先存3年，再存2年 */
    p4 = p * pow(1 + r1, 5);                     /* 存1年期，连续存5次 */
    p5 = p * pow(1 + r0 / 4, 4 * 5);             /* 存活期，每季度计息 */
    
    printf("p1=%f\n", p1);
    printf("p2=%f\n", p2);
    printf("p3=%f\n", p3);
    printf("p4=%f\n", p4);
    printf("p5=%f\n", p5);
    return 0;
}